import pytest
import numpy as np
from benchmark.corpus_registry import validate_sample_schema, compute_content_hash, normalize_sample
from benchmark.adapters.external_adapters import adapt_raid_sample, adapt_semeval_sample
from benchmark.evaluate import compute_bootstrap_ci, compute_metrics

def test_validate_sample_schema_valid():
    sample = {
        "text": "This is a valid academic prose sample.",
        "label": "human",
        "source_group_id": "group_001",
        "provenance": {
            "source_name": "Test Archive",
            "dataset_license": "MIT"
        }
    }
    is_valid, err = validate_sample_schema(sample)
    assert is_valid is True
    assert err is None

def test_validate_sample_schema_invalid():
    sample = {
        "text": "",
        "label": "unknown_label"
    }
    is_valid, err = validate_sample_schema(sample)
    assert is_valid is False
    assert "Missing required fields" in err

def test_normalize_sample_hash():
    sample = {
        "text": "Unique sample text for content hashing.",
        "label": "ai",
        "source_group_id": "group_002",
        "provenance": {
            "source_name": "AI Test Data",
            "dataset_license": "Apache-2.0"
        }
    }
    norm = normalize_sample(sample)
    assert norm["label"] == 1
    assert norm["content_hash"] == compute_content_hash(sample["text"])
    assert "sample_id" in norm

def test_adapt_raid_sample():
    raw = {
        "generation": "Sample text generated by LLM.",
        "model": "gpt-4",
        "domain": "history",
        "attack": "none"
    }
    adapted = adapt_raid_sample(raw)
    assert adapted["label"] == 1
    assert adapted["source_group_id"] == "raid_history_none"
    assert adapted["provenance"]["source_name"] == "RAID Benchmark Dataset"

def test_adapt_semeval_sample():
    raw = {
        "text": "SemEval human text sample.",
        "label": 0,
        "model": "human",
        "domain": "biology"
    }
    adapted = adapt_semeval_sample(raw)
    assert adapted["label"] == 0
    assert adapted["source_group_id"] == "semeval_human"

def test_compute_bootstrap_ci():
    rng = np.random.RandomState(42)
    y_true = np.array([0]*15 + [1]*15)
    y_prob = np.array(list(rng.uniform(0.0, 0.4, 15)) + list(rng.uniform(0.6, 1.0, 15)))
    
    ci = compute_bootstrap_ci(y_true, y_prob, n_bootstraps=50)
    assert "auroc_ci" in ci
    assert ci["auroc_ci"][0] is not None
    assert ci["auroc_ci"][1] is not None
    assert ci["auroc_ci"][0] <= ci["auroc_ci"][1]

def test_compute_metrics_single_class():
    y_true = [0, 0, 0, 0]
    y_prob = [0.1, 0.2, 0.15, 0.3]
    m = compute_metrics(y_true, y_prob)
    assert m["auroc"] is None
    assert m["auprc"] is None
    assert m["confusion_matrix"]["accuracy"] == 1.0
